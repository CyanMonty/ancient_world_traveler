#!/usr/bin/env node
/*
 * Generates js/data/land.js — Natural Earth 1:50m land polygons clipped to the
 * Mediterranean / Near East viewport, so the map works without any tile server.
 *
 *   npm install && npm run build:land
 */
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');

const BBOX = { west: -35, east: 80, south: 5, north: 65 };
const PRECISION = 3;

const topo = require('world-atlas/land-50m.json');
const land = topojson.feature(topo, topo.objects.land);

// Sutherland–Hodgman clip of one ring against an axis-aligned rectangle.
function clipRing(ring) {
  const edges = [
    { inside: (p) => p[0] >= BBOX.west, cut: (a, b) => cutX(a, b, BBOX.west) },
    { inside: (p) => p[0] <= BBOX.east, cut: (a, b) => cutX(a, b, BBOX.east) },
    { inside: (p) => p[1] >= BBOX.south, cut: (a, b) => cutY(a, b, BBOX.south) },
    { inside: (p) => p[1] <= BBOX.north, cut: (a, b) => cutY(a, b, BBOX.north) },
  ];
  let out = ring;
  for (const e of edges) {
    const input = out;
    out = [];
    if (!input.length) break;
    let prev = input[input.length - 1];
    for (const cur of input) {
      if (e.inside(cur)) {
        if (!e.inside(prev)) out.push(e.cut(prev, cur));
        out.push(cur);
      } else if (e.inside(prev)) {
        out.push(e.cut(prev, cur));
      }
      prev = cur;
    }
  }
  return out;
}
function cutX(a, b, x) {
  const t = (x - a[0]) / (b[0] - a[0]);
  return [x, a[1] + t * (b[1] - a[1])];
}
function cutY(a, b, y) {
  const t = (y - a[1]) / (b[1] - a[1]);
  return [a[0] + t * (b[0] - a[0]), y];
}

const round = (v) => Math.round(v * 10 ** PRECISION) / 10 ** PRECISION;

const polygons = [];
const geoms = land.features.flatMap((f) =>
  f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]
);
for (const poly of geoms) {
  const rings = [];
  for (const ring of poly) {
    const clipped = clipRing(ring)
      .map((p) => [round(p[0]), round(p[1])])
      .filter((p, i, arr) => i === 0 || p[0] !== arr[i - 1][0] || p[1] !== arr[i - 1][1]);
    if (clipped.length >= 4) rings.push(clipped);
  }
  // keep polygon only if its outer ring survived
  if (rings.length && clipRing(poly[0]).length >= 4) polygons.push(rings);
}

const geojson = {
  type: 'Feature',
  properties: { source: 'Natural Earth 1:50m land (public domain) via world-atlas' },
  geometry: { type: 'MultiPolygon', coordinates: polygons },
};

const outFile = path.join(__dirname, '..', 'js', 'data', 'land.js');
fs.writeFileSync(
  outFile,
  '// Generated by tools/build-land.js — do not edit by hand.\n' +
    'window.AWT = window.AWT || {};\n' +
    'AWT.land = ' + JSON.stringify(geojson) + ';\n'
);
console.log(`Wrote ${outFile} (${polygons.length} polygons, ${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`);

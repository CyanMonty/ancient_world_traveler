#!/usr/bin/env node
/*
 * Builds js/data/bundle.js from the JSON files in data/.
 *
 * The JSON files are the source of truth (a graph of nodes and edges plus supporting data).
 * Browsers will not fetch local JSON when index.html is opened straight from disk, so the
 * app loads this generated bundle instead. Run after editing anything in data/:
 *
 *   npm run build:data          rebuild the bundle (and tidy the JSON formatting)
 *   npm run build:data -- --check   fail if the bundle is out of date (used by the tests)
 *
 * Data files:
 *   data/nodes.json       places: id, modern name, lat/lng, kind, eras [{from, to, name, rank, note, exactFrom, exactTo}]
 *   data/edges.json       routes: id, from, to, mode, name, desc, sources, via, flags, spans [{from, to, exactFrom, exactTo}], overrides
 *   data/waypoints.json   named points used to draw edges
 *   data/zones.json       climate & terrain zones used by the edge-weight effects
 *   data/narratives.json  descriptions of the five mapped periods
 *   data/config.json      timeline range, traveller speeds, winding factors
 *   data/powers.json, data/regions.json  political powers and region ownership timelines (see build-regions)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const OUT = path.join(ROOT, 'js', 'data', 'bundle.js');

/** JSON with 2-space indent, but short arrays/objects kept on one line, for readable diffs. */
function prettyJson(value, indent = '') {
  const flat = JSON.stringify(value);
  if (flat.length <= 110 || value === null || typeof value !== 'object') return flat;
  const next = indent + '  ';
  if (Array.isArray(value)) return '[\n' + value.map((v) => next + prettyJson(v, next)).join(',\n') + '\n' + indent + ']';
  return '{\n' + Object.entries(value).map(([k, v]) => `${next}${JSON.stringify(k)}: ${prettyJson(v, next)}`).join(',\n') + '\n' + indent + '}';
}

const FILES = ['config', 'nodes', 'edges', 'waypoints', 'zones', 'narratives', 'powers', 'regions'];

function readData() {
  const d = {};
  for (const f of FILES) {
    const file = path.join(DATA, f + '.json');
    if (fs.existsSync(file)) d[f] = JSON.parse(fs.readFileSync(file, 'utf8'));
  }
  return d;
}

/** Basic structural validation; deeper checks live in tests/validate.js. */
function validate(d) {
  const errors = [];
  const ids = new Set();
  for (const n of d.nodes) {
    if (ids.has(n.id)) errors.push(`duplicate node ${n.id}`);
    ids.add(n.id);
    for (let i = 0; i < n.eras.length; i++) {
      const e = n.eras[i];
      if (e.from > e.to) errors.push(`node ${n.id} era ${i} ends before it starts`);
      if (i && e.from <= n.eras[i - 1].to) errors.push(`node ${n.id} eras overlap`);
    }
  }
  const eids = new Set();
  for (const e of d.edges) {
    if (eids.has(e.id)) errors.push(`duplicate edge ${e.id}`);
    eids.add(e.id);
    if (!ids.has(e.from) || !ids.has(e.to)) errors.push(`edge ${e.id} references a missing node`);
    for (const w of e.via || []) if (!d.waypoints[w]) errors.push(`edge ${e.id} unknown waypoint ${w}`);
    for (const s of e.spans) if (s.from > s.to) errors.push(`edge ${e.id} span ends before it starts`);
  }
  return errors;
}

function build({ regionsBuilder } = {}) {
  const d = readData();
  const errors = validate(d);
  if (errors.length) throw new Error('Data errors:\n  ' + errors.join('\n  '));
  const regions = d.regions && regionsBuilder ? regionsBuilder(d) : null;
  const parts = [
    '// Generated by tools/build-data.js from data/*.json — do not edit by hand.',
    'window.AWT = window.AWT || {};',
    `AWT.config = ${JSON.stringify(d.config)};`,
    `AWT.travelers = AWT.config.travelers;`,
    `AWT.windingFactor = AWT.config.windingFactor;`,
    `AWT.cities = ${JSON.stringify(d.nodes)};`,
    `AWT.routes = ${JSON.stringify(d.edges)};`,
    `AWT.waypoints = ${JSON.stringify(d.waypoints)};`,
    `AWT.zones = ${JSON.stringify(d.zones)};`,
    `AWT.periods = ${JSON.stringify(d.narratives)};`,
  ];
  if (d.powers) parts.push(`AWT.powers = ${JSON.stringify(d.powers)};`);
  if (regions) parts.push(`AWT.regions = ${JSON.stringify(regions)};`);
  return { bundle: parts.join('\n') + '\n', data: d };
}

function formatDataFiles(d) {
  for (const f of FILES) {
    if (!d[f]) continue;
    const file = path.join(DATA, f + '.json');
    const text = prettyJson(d[f]) + '\n';
    if (fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
  }
}

module.exports = { build, prettyJson, readData, OUT };

if (require.main === module) {
  let regionsBuilder = null;
  try {
    regionsBuilder = require('./build-regions.js').buildRegions;
  } catch (e) {
    if (e.code !== 'MODULE_NOT_FOUND') throw e;
  }
  const { bundle, data } = build({ regionsBuilder });
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== bundle) {
      console.error('js/data/bundle.js is out of date — run `npm run build:data`.');
      process.exit(1);
    }
    console.log('bundle up to date');
  } else {
    formatDataFiles(data);
    fs.writeFileSync(OUT, bundle);
    console.log(`Wrote ${OUT} (${(bundle.length / 1024).toFixed(0)} KB): ${data.nodes.length} nodes, ${data.edges.length} edges`);
  }
}

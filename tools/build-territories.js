#!/usr/bin/env node
/*
 * Builds js/data/territories.js from tools/territories.src.js.
 * In each period, every power loses any land already claimed by a power listed
 * before it, so the output polygons never overlap.
 *
 *   npm install && npm run build:territories
 */
const fs = require('fs');
const path = require('path');
const turf = require('@turf/turf');
const src = require('./territories.src.js');

const PRECISION = 3;
const round = (v) => Math.round(v * 10 ** PRECISION) / 10 ** PRECISION;

function close(ring) {
  const r = ring.map(([x, y]) => [x, y]);
  const [a, b] = [r[0], r[r.length - 1]];
  if (a[0] !== b[0] || a[1] !== b[1]) r.push([a[0], a[1]]);
  return r;
}

function toFeature(rings) {
  const polys = rings.map((ring) => turf.polygon([close(ring)]));
  let f = polys[0];
  for (const p of polys.slice(1)) f = turf.union(turf.featureCollection([f, p]));
  return f;
}

function roundGeometry(geom) {
  const rr = (ring) => ring.map(([x, y]) => [round(x), round(y)]);
  if (geom.type === 'Polygon') return { type: 'MultiPolygon', coordinates: [geom.coordinates.map(rr)] };
  return { type: 'MultiPolygon', coordinates: geom.coordinates.map((p) => p.map(rr)) };
}

const out = {};
for (const [period, powers] of Object.entries(src.periods)) {
  let claimed = null;
  out[period] = [];
  for (const p of powers) {
    let f = toFeature(p.rings);
    if (claimed) f = turf.difference(turf.featureCollection([f, claimed]));
    if (!f) {
      console.warn(`  ! ${period}/${p.id} is entirely covered by earlier powers`);
      continue;
    }
    claimed = claimed ? turf.union(turf.featureCollection([claimed, f])) : f;
    out[period].push({ id: p.id, name: p.name, color: p.color, note: p.note, geometry: roundGeometry(f.geometry) });
  }
}

const outFile = path.join(__dirname, '..', 'js', 'data', 'territories.js');
fs.writeFileSync(
  outFile,
  '// Generated by tools/build-territories.js from tools/territories.src.js — do not edit by hand.\n' +
    'window.AWT = window.AWT || {};\n' +
    'AWT.territories = ' + JSON.stringify(out) + ';\n'
);
const counts = Object.entries(out).map(([k, v]) => `${k}: ${v.length}`).join(', ');
console.log(`Wrote ${outFile} (${(fs.statSync(outFile).size / 1024).toFixed(0)} KB) — ${counts}`);
